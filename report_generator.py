
from reportlab.lib.pagesizes import letter
from reportlab.pdfgen import canvas
from reportlab.lib.units import inch
from io import BytesIO
from PIL import Image
import datetime

def generate_pdf_report(tester_name, patient_name, patient_id, current_time, gender, predicted_age, original_image, preprocessed_image):
    buffer = BytesIO()
    c = canvas.Canvas(buffer, pagesize=letter)
    width, height = letter
    
    # Header
    c.setFont("Helvetica-Bold", 16)
    c.drawString(inch, height - inch, "Pediatric Bone Age Assessment Report")
    
    # Assessment Details
    c.setFont("Helvetica-Bold", 12)
    c.drawString(inch, height - 1.5 * inch, "Assessment Details:")
    c.setFont("Helvetica", 12)
    c.drawString(inch, height - 1.75 * inch, f"Tester Name: {tester_name}")
    c.drawString(inch, height - 2 * inch, f"Date of Assessment: {current_time.strftime('%Y-%m-%d %H:%M:%S')}")
    
    # Patient Information
    c.setFont("Helvetica-Bold", 12)
    c.drawString(inch, height - 2.5 * inch, "Patient Information:")
    c.setFont("Helvetica", 12)
    c.drawString(inch, height - 2.75 * inch, f"Patient Name: {patient_name if patient_name else 'Anonymous'}")
    if patient_id:
        c.drawString(inch, height - 3 * inch, f"Patient ID: {patient_id}")
    c.drawString(inch, height - 3.25 * inch if patient_id else height - 3 * inch, f"Gender: {gender}")
    
    # Results
    c.setFont("Helvetica-Bold", 12)
    c.drawString(inch, height - 3.75 * inch, "Assessment Results:")
    c.setFont("Helvetica", 12)
    c.drawString(inch, height - 4 * inch, f"Predicted Bone Age: {predicted_age:.2f} months")
    c.drawString(inch, height - 4.25 * inch, "Methodology: Computer-assisted analysis of hand X-ray image using ResNet50 methodology.")
    c.drawString(inch, height - 4.5 * inch, "Note: This is an automated estimation and should be reviewed by a qualified medical professional.")
    
    # Images
    c.setFont("Helvetica-Bold", 12)
    c.drawString(inch, height - 5.25 * inch, "Images:")
    
    # Embed original image (PIL Image)
    c.drawInlineImage(original_image, inch, height - 7.5 * inch, width=2*inch, height=2*inch)
    c.drawString(inch, height - 7.75 * inch, "Original X-ray Image")
    
    # Embed preprocessed image (convert numpy to PIL if needed)
    preproc_pil = Image.fromarray(preprocessed_image)
    c.drawInlineImage(preproc_pil, 4 * inch, height - 7.5 * inch, width=2*inch, height=2*inch)
    c.drawString(4 * inch, height - 7.75 * inch, "Preprocessed Image")
    
    # Footer
    c.setFont("Helvetica-Oblique", 10)
    c.drawString(inch, inch, "Generated by Pediatric Bone Age Prediction System. For diagnostic use only under medical supervision.")
    
    c.save()
    buffer.seek(0)
    return buffer